//! Experimental turn optimizer (`experimental.turn_optimizer`): a layer between the user and the
//! main model. The `turn_drafter` role restates a user message, a new turn or steering, as a
//! structured prompt. The main model receives the typed message verbatim as the authoritative
//! request, with the draft attached beneath it in a labeled `turn_draft` notice; the typed text is
//! also kept under `dial_turn_draft`, so transcripts, resume and memory show what the user wrote.
//!
//! Short or already structured messages are sent as typed without a drafter request
//! ([`worth_drafting`]). Drafting fails closed: a failed, cancelled, truncated or empty draft fails
//! the turn and nothing reaches the main model. Harness-generated turns (goal continuations) and
//! hermetic agents are not drafted.
//! Interactive surfaces require review before delivery; unattended surfaces retain automatic
//! delivery of valid drafts. Rejection never falls back to sending the message without review.

use crate::agent::*;
use crate::llm::model_config::TURN_DRAFTER;
use crate::storage::session::TURN_DRAFT_KEY;

mod fidelity;

/// Output budget for one drafted prompt: structured text and diagrams, not an answer.
const DRAFT_MAX_TOKENS: u32 = 8192;
/// Earlier assistant replies the drafter sees, so references such as "do that" resolve.
const CONTEXT_REPLIES: usize = 2;
const CONTEXT_REPLY_CHARS: usize = 2000;
const CONTEXT_INSTRUCTION_CHARS: usize = 6000;
/// Messages shorter than this are sent as typed: there is little to structure, and a drafter
/// request plus review costs more than it adds.
const MIN_DRAFT_CHARS: usize = 200;
/// List items that mark a message as already structured.
const STRUCTURED_ITEMS: usize = 3;

/// Whether a message gets a draft: at least [`MIN_DRAFT_CHARS`] long and not already structured
/// (a Markdown heading, or [`STRUCTURED_ITEMS`] list items, outside code fences).
pub(in crate::agent) fn worth_drafting(typed: &str) -> bool {
    typed.trim().chars().count() >= MIN_DRAFT_CHARS && !already_structured(typed)
}

fn already_structured(text: &str) -> bool {
    let mut fenced = false;
    let mut items = 0;
    for line in text.lines().map(str::trim_start) {
        if line.starts_with("```") || line.starts_with("~~~") {
            fenced = !fenced;
            continue;
        }
        if fenced {
            continue;
        }
        let heading = line.trim_start_matches('#');
        if heading.len() < line.len() && line.len() - heading.len() <= 6 && heading.starts_with(' ')
        {
            return true;
        }
        let ordered = line.split_once(['.', ')']).is_some_and(|(number, rest)| {
            !number.is_empty()
                && number.chars().all(|c| c.is_ascii_digit())
                && rest.starts_with(' ')
        });
        if ordered || line.starts_with("- ") || line.starts_with("* ") || line.starts_with("+ ") {
            items += 1;
        }
    }
    items >= STRUCTURED_ITEMS
}

/// Who wrote a turn's text. Only user-authored turns pass through the drafter.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(in crate::agent) enum TurnOrigin {
    /// Typed by the user (or sent by a client on the user's behalf).
    User,
    /// Generated by the harness itself, such as a goal continuation prompt.
    Harness,
    /// Resume the existing task for peer context, without recording a new user instruction.
    Peer,
    /// Resume for an approved application watch, without promoting logs into instructions.
    Monitor,
}

/// The drafter request. The user's message and its context travel as JSON data, never as
/// instructions addressed to the drafter.
pub(in crate::agent) fn draft_request(
    active_instruction: &str,
    history: &[Value],
    user_message: &str,
    diagrams: bool,
) -> Chat {
    let mut recent: Vec<Value> = history
        .iter()
        .rev()
        .filter(|message| message["role"] == "assistant")
        .filter_map(|message| message["content"].as_str())
        .filter(|text| !text.trim().is_empty())
        .take(CONTEXT_REPLIES)
        .map(|text| {
            json!(crate::agent::window::prompt::truncate_chars(
                text,
                CONTEXT_REPLY_CHARS
            ))
        })
        .collect();
    recent.reverse();
    Chat {
        messages: vec![
            json!({"role":"system","content":crate::agent::prompts::turn_drafter::system(diagrams)}),
            json!({"role":"user","content":json!({
                "active_instruction":crate::agent::window::prompt::truncate_chars(
                    active_instruction,
                    CONTEXT_INSTRUCTION_CHARS,
                ),
                "recent_assistant":recent,
                "user_message":user_message,
            }).to_string()}),
        ],
        tools: vec![],
        temperature: 0.0,
        max_tokens: DRAFT_MAX_TOKENS,
        seed: None,
    }
}

/// Attach the draft beneath the typed message (and the attachment blocks `@references` appended
/// to it) as a labeled interpretation. The typed text stays first and authoritative; the draft is
/// quoted so it cannot close its notice, and the typed text is also kept under `dial_turn_draft`.
pub(in crate::agent) fn apply_draft(message: &mut Value, typed: &str, drafted: &str) {
    use crate::agent::prompts::recovery::{notice, quoted};
    let content = message["content"].as_str().unwrap_or(typed);
    let interpretation = notice(
        "turn_draft",
        &format!(
            "{}\n\n{}",
            crate::agent::prompts::turn_drafter::INTERPRETATION_LABEL,
            quoted(drafted)
        ),
    );
    message["content"] = json!(format!("{content}\n\n{interpretation}"));
    message[TURN_DRAFT_KEY] = json!({"original": typed});
}

impl Agent<'_> {
    /// Whether user messages pass through the drafter. Hermetic agents keep their exact input.
    pub(in crate::agent) fn turn_optimizer_enabled(&self) -> bool {
        self.config.experimental.turn_optimizer && !self.hermetic
    }

    /// Draft one user message with the `turn_drafter` role, which follows the main model when
    /// unassigned. `None` means the message goes as typed ([`worth_drafting`]). Fails closed:
    /// the error says the message was not sent to the main model.
    pub(in crate::agent) fn draft_message(
        &mut self,
        main: &mut Backend,
        typed: &str,
        step: u32,
        ui: &mut dyn Ui,
    ) -> Result<Option<String>> {
        if !worth_drafting(typed) {
            ui.event(&crate::agent::ui::ui_event::UiEvent::new(
                crate::agent::ui::ui_event::EventKind::Draft,
                "Turn optimizer: sending your message as typed (short or already structured).",
            ));
            return Ok(None);
        }
        ui.event(&crate::agent::ui::ui_event::UiEvent::new(
            crate::agent::ui::ui_event::EventKind::Draft,
            "Turn optimizer: drafting a structured prompt from your message.",
        ));
        let instruction = self.session.control_state()["current_instruction"]
            .as_str()
            .unwrap_or("")
            .to_owned();
        let chat = draft_request(
            &instruction,
            &self.session.messages(),
            typed,
            self.config.experimental.turn_drafter_diagrams,
        );
        let drafted = self
            .role_chat(
                main,
                TURN_DRAFTER,
                llm::usage::Purpose::Auxiliary,
                &chat,
                ui,
            )
            .context("turn drafter failed; your message was not sent to the main model")?;
        let drafted = drafted.trim();
        ensure!(
            !drafted.is_empty(),
            "turn drafter returned an empty prompt; your message was not sent to the main model"
        );
        ensure!(
            fidelity::preserves(typed, drafted),
            "turn draft did not preserve explicit verbatim material; your message was not sent to the main model"
        );
        ui.extension_panel("Turn drafter · proposed instruction", drafted);
        if !ui.review_turn_draft(drafted, &self.interrupt) {
            let interrupted = self.interrupt.load(Ordering::Acquire);
            return Err(DraftCancelled { interrupted }.into());
        }
        if self.interrupt.load(Ordering::Acquire) {
            return Err(DraftCancelled { interrupted: true }.into());
        }
        self.record(
            step,
            "turn_drafted",
            json!({"typed_chars":typed.chars().count(),"drafted_chars":drafted.chars().count()}),
        )?;
        Ok(Some(drafted.to_owned()))
    }

    /// Draft and journal steering that was deferred while the main stream held the backend, in
    /// submission order. Returns whether anything was journaled. When a draft fails, that message
    /// is not sent (the error says so); the messages queued after it stay queued and are drafted
    /// before the next turn's message, so no undrafted text reaches the main model and none is lost.
    pub(in crate::agent) fn draft_deferred_steering(
        &mut self,
        main: &mut Backend,
        ui: &mut dyn Ui,
    ) -> Result<bool> {
        let mut queued = std::mem::take(&mut self.undrafted_steering).into_iter();
        let mut journaled = false;
        while let Some((mut message, text)) = queued.next() {
            let drafted = match self.draft_message(main, &text, self.cur_step, ui) {
                Ok(drafted) => drafted,
                Err(error) => {
                    // An interrupt stops the steering queued behind this message too; a rejected
                    // review or a drafter failure loses only this message, and later messages
                    // stay queued for their own drafts.
                    let interrupted = error
                        .downcast_ref::<DraftCancelled>()
                        .is_some_and(|cancelled| cancelled.interrupted);
                    let kept: Vec<_> = if interrupted {
                        Vec::new()
                    } else {
                        queued.collect()
                    };
                    let later = kept.len();
                    // Anything queued while drafting stays behind the kept messages.
                    let newer = std::mem::replace(&mut self.undrafted_steering, kept);
                    self.undrafted_steering.extend(newer);
                    return Err(error.context(if later == 0 {
                        "1 steering message was not sent to the main model".to_owned()
                    } else {
                        format!(
                            "1 steering message was not sent to the main model; {later} later message(s) stay queued and are drafted before your next message"
                        )
                    }));
                }
            };
            if let Some(drafted) = drafted {
                apply_draft(&mut message, &text, &drafted);
            }
            // The typed text stays the current instruction; the draft only travels with it.
            self.journal_steering(message, &text)?;
            ui.steering_applied(&text);
            journaled = true;
        }
        Ok(journaled)
    }

    /// Steering left over from an earlier turn (one that was interrupted, for example) is
    /// drafted before a new turn's message, keeping submission order.
    pub(in crate::agent) fn draft_leftover_steering(&mut self, ui: &mut dyn Ui) -> Result<()> {
        if self.undrafted_steering.is_empty() {
            return Ok(());
        }
        let mut backend = self.backend.take().context("backend is already in use")?;
        let result = self.draft_deferred_steering(&mut backend, ui);
        self.backend = Some(backend);
        result.map(drop)
    }

    /// Draft the text of a new user turn. The backend is borrowed only for the drafting request.
    pub(in crate::agent) fn draft_turn_text(
        &mut self,
        typed: &str,
        ui: &mut dyn Ui,
    ) -> Result<Option<String>> {
        let mut backend = self.backend.take().context("backend is already in use")?;
        let result = self.draft_message(&mut backend, typed, 0, ui);
        self.backend = Some(backend);
        result
    }
}

/// The user rejected a draft in review, or interrupted: nothing is sent. Only an interrupt also
/// drops the steering queued behind it.
#[derive(Debug)]
struct DraftCancelled {
    interrupted: bool,
}
impl std::fmt::Display for DraftCancelled {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("turn draft cancelled; your message was not sent to the main model")
    }
}
impl std::error::Error for DraftCancelled {}

